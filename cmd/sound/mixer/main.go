// Command mixer is the audio demo a game would recognise: a three-minute music
// track streaming under short one-shots that overlap it, each set on its own
// Bus, driven from the keyboard, with the live Voice table on screen.
//
//	go run ./cmd/sound/mixer
//
// Every other sound demo here isolates one decision and prints it to a console.
// This one puts the two residency tiers in one mixer at the same time, which is
// the ordinary case, and it opens a window — because a demo you can drive is
// worth one, and because cog's input binds to gogpu's window, so a demo with no
// window has no keyboard.
//
// # What it is evidence for
//
// **The streamed tier exists and nothing has to ask for it.** The music is
// assets/music/pleasant-moments.ogg: 176.181 s of stereo 44.1 kHz, 2.7 MiB
// encoded and 59.3 MiB decoded, a ratio of 21.8x. otosound's and jssound's
// DecodedClipLimit defaults to 512 KiB — 1.49 s of stereo 44.1 kHz — so the
// track is three orders of magnitude over the line and streams with no
// configuration at all. The one-shot beside it is the 1.1 s cut of the same
// recording, which is well under the limit and is decoded once and held. Both
// are played through one call, and see play for why there is no branch there.
//
// **Voices overlap, and the cap is a band rather than a weight.** The engine is
// composed with MaxVoices at 12, and B records sixteen plays into a single
// tick, so the cap takes at least four of them in the flush that starts the
// rest - five while the music holds a slot of its own. The music is at
// Priority 1 and the one-shots at 0, so the music is never among them however
// loud the burst is; that is cmd/sound/crowd's subject, shown here as the
// thing it actually protects.
//
// **A Bus volume moves one set of rows and not the other.** Each row's
// audibility is drawn as a bar, so turning the music Bus down moves one bar and
// leaves eleven where they were. That is the settings-screen case SetBus exists
// for, and it is the first thing a player notices in a real game.
//
// **Nothing on screen is the demo's own idea of what is happening.** Every
// number in the table is read back off kernel.Read[*sound.Voices],
// [*sound.Buses], [*sound.Clips] and [*sound.Device] — what the engine derived,
// not what this program commanded. Run it on a machine with no sound card and
// the Device row says not ready while every playhead keeps moving, because a
// Voice's clock is the engine's rather than the device's.
//
// # Keys
//
//	M          music on / off
//	SPACE      fire one one-shot; 2 is the same key by another name
//	1 2 3      fire one one-shot at pitch 0.70 / 1.00 / 1.45
//	B          fire sixteen at once, which is more Voices than the engine has
//	S          suspend / resume the music Voice on its own
//	LEFT RIGHT seek the music by -10 s / +10 s
//	[ ]        music Bus volume down / up
//	, .        effects Bus volume down / up
//	- =        master down / up
//	P          pause / resume the engine
//	ESC        quit
//
// In a browser the keys reach the demo only once the canvas has focus: gogpu
// binds keydown on the canvas element rather than on the document, which is why
// cmd/web/index.html gives it a tabindex and focuses it. And a page makes no
// sound at all until a gesture resumes its AudioContext, so the Device row
// reads not-ready until the first click. jssound installs that listener itself;
// the demo only says which state it is in.
